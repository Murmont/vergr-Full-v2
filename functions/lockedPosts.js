/**
 * Creating a locked post: the upload that never gets a public URL.
 *
 * `getR2UploadUrl` presigns into a public prefix and hands back a
 * `getPublicBase()` URL, which is exactly right for ordinary media and exactly
 * wrong here. A locked post whose bytes sit on a guessable CDN URL is not
 * locked, it is merely undisplayed, and the first person to read the document
 * gets it for free.
 *
 * So locked media goes to `locked/{uid}/...`, a prefix with no public base, and
 * the object key is written to `users/{uid}/private/lockedPostFiles`, which no
 * client can read. The only way back to the bytes is `getAccess` in
 * entitlements.js minting a 5-minute presigned GET after it has proven the
 * caller paid.
 *
 * ## The preview is generated by the CREATOR's device, not here
 *
 * A deliberate divergence from the plan, which said server-side. The property
 * that has to hold is that a VIEWER never receives full-resolution bytes. The
 * creator's own phone already has the image; it is theirs. So it downscales to a
 * thumbnail and blurs THAT, and uploads the result as an ordinary public object.
 * Same guarantee, no image library in the functions bundle, no compute cost.
 *
 * A blur applied on the VIEWER's device remains forbidden and always will be:
 * that is a CSS filter over bytes the phone has already downloaded, and it is
 * undone by a screenshot of the network tab.
 *
 * ## Locking is create-time only
 *
 * There is no `lockExistingPost`. An existing post's media is already on a
 * public, immutable, CDN-cached URL, so "locking" it would hide it in the UI
 * while leaving the bytes exactly as reachable as before. Offering that would be
 * a lie told in a checkbox. `createLockedPost` is the only way in.
 */
const functions = require('firebase-functions/v2');
const { HttpsError } = require('firebase-functions/v2/https');
const { getFirestore, FieldValue } = require('firebase-admin/firestore');
const { S3Client, PutObjectCommand, GetObjectCommand } = require('@aws-sdk/client-s3');
const { getSignedUrl } = require('@aws-sdk/s3-request-presigner');
const crypto = require('crypto');

const REGION = 'europe-west1';
const db = getFirestore('vgrdb');

const R2_SECRETS = ['R2_ACCOUNT_ID', 'R2_ACCESS_KEY_ID', 'R2_SECRET_ACCESS_KEY', 'R2_BUCKET', 'R2_PUBLIC_BASE'];

/** Mirrors entitlements.js. Same numbers, plan section 6.3. */
const MIN_PRICE_COINS = 50;
const MAX_PRICE_COINS = 10_000;

/**
 * MIME allowlist, exact match, no parameters.
 *
 * R2's allowlist exact-matches, so a MediaRecorder content type carrying a
 * `;codecs=` suffix fails the signature silently. Callers strip it; this refuses
 * it outright so the failure is loud instead.
 */
const ALLOWED_TYPES = [
  'image/jpeg', 'image/png', 'image/webp',
  'video/mp4', 'video/webm',
];

const SIZE_CAPS = { free: 200 * 1024 * 1024, lite: 1024 * 1024 * 1024, pro: 5 * 1024 * 1024 * 1024 };

const env = (name) => (process.env[name] || '').replace(/[\s\r\n]+$/g, '').trim();
const bucket = () => env('R2_BUCKET') || 'vergr-media';
const publicBase = () => env('R2_PUBLIC_BASE') || 'https://cdn.vergr.app';

function r2Client() {
  return new S3Client({
    region: 'auto',
    endpoint: `https://${env('R2_ACCOUNT_ID')}.r2.cloudflarestorage.com`,
    credentials: {
      accessKeyId: env('R2_ACCESS_KEY_ID'),
      secretAccessKey: env('R2_SECRET_ACCESS_KEY'),
    },
  });
}

function requireAuth(request) {
  const uid = request.auth?.uid;
  if (!uid) throw new HttpsError('unauthenticated', 'Sign in required.');
  return uid;
}

async function planFor(uid) {
  const snap = await db.collection('users').doc(uid).get();
  const u = snap.exists ? snap.data() : {};
  const isAdmin = u.role === 'admin' || (u.email || '').toLowerCase() === 'vergenerd@gmail.com';
  if (isAdmin) return 'pro';
  const tier = u.subscription?.tier || u.subscription || 'free';
  return ['free', 'lite', 'pro'].includes(tier) ? tier : 'free';
}

/**
 * Presign a PUT for one locked file, plus one for its public blurred preview.
 *
 * Both are handed out together because they are two halves of one upload and a
 * client that got only the first would produce a locked post nobody can see the
 * shape of. The preview key is public and permanent; the media key is returned
 * so the client can pass it back to `createLockedPost`, and is meaningless on
 * its own since nothing serves that prefix.
 */
exports.getLockedUploadUrl = functions.https.onCall(
  { region: REGION, cors: true, secrets: R2_SECRETS },
  async (request) => {
    const uid = requireAuth(request);
    const contentType = String(request.data?.contentType || '');
    const sizeBytes = Math.floor(Number(request.data?.sizeBytes) || 0);

    if (!ALLOWED_TYPES.includes(contentType)) {
      throw new HttpsError('invalid-argument', `Content type ${contentType} not allowed.`);
    }
    if (sizeBytes <= 0) throw new HttpsError('invalid-argument', 'sizeBytes required.');

    const plan = await planFor(uid);
    const cap = SIZE_CAPS[plan];
    if (sizeBytes > cap) {
      throw new HttpsError(
        'resource-exhausted',
        `File exceeds your ${plan} plan limit of ${Math.round(cap / 1024 / 1024)}MB.`,
      );
    }

    const stamp = `${Date.now()}_${crypto.randomBytes(6).toString('hex')}`;
    const ext = contentType.split('/')[1];
    // NO public base for this one. The prefix is the security boundary.
    const mediaKey = `locked/${uid}/${stamp}.${ext}`;
    const previewKey = `lockedpreview/${uid}/${stamp}.jpg`;

    const cacheControl = 'public, max-age=31536000, immutable';
    const client = r2Client();

    const [mediaUploadUrl, previewUploadUrl] = await Promise.all([
      getSignedUrl(client, new PutObjectCommand({
        Bucket: bucket(),
        Key: mediaKey,
        ContentType: contentType,
        ContentLength: sizeBytes,
        CacheControl: cacheControl,
      }), { expiresIn: 300 }),
      getSignedUrl(client, new PutObjectCommand({
        Bucket: bucket(),
        Key: previewKey,
        ContentType: 'image/jpeg',
        CacheControl: cacheControl,
      }), { expiresIn: 300 }),
    ]);

    return {
      mediaUploadUrl,
      mediaKey,
      previewUploadUrl,
      previewUrl: `${publicBase()}/${previewKey}`,
      cacheControl,
    };
  },
);

/**
 * Create the post, and file the private key where only the server can find it.
 *
 * Both writes go in one batch. A post that exists without its key entry is
 * unopenable even by the person who made it, and a key entry without its post is
 * an orphan nothing will ever clean up.
 */
exports.createLockedPost = functions.https.onCall(
  { region: REGION, cors: true, secrets: [...R2_SECRETS, 'GEMINI_POST_IMAGE_KEY'] },
  async (request) => {
    const uid = requireAuth(request);

    const mediaKey = String(request.data?.mediaKey || '');
    const previewUrl = String(request.data?.previewUrl || '');
    const caption = String(request.data?.caption || '').slice(0, 2000);
    const priceCoins = Math.floor(Number(request.data?.priceCoins) || 0);
    const isVideo = request.data?.isVideo === true;
    // Adult marker. Only ever 'nsfw' or absent, never a literal 'general', so
    // existing documents and ordinary posts read identically (absent = safe).
    // The seller declares it here; the priced-media scanner can correct it
    // later, and entitlements.js refuses to serve it without a verified age.
    let contentRating = request.data?.contentRating === 'nsfw' ? 'nsfw' : null;
    // Set by the scanner below when it sees adult content the seller did not
    // declare. Declared here because the scan runs before the document write.
    let autoRating = null;
    const audience = ['public', 'followers', 'subscribers'].includes(request.data?.audience)
      ? request.data.audience
      : 'public';

    // Shape of the media, measured on the sender's device. A feed card and a
    // profile tile both need to reserve the post's real proportions before the
    // blurred preview has loaded, or the layout jumps. Clamped because these
    // only ever produce a ratio and an absurd value would break the layout.
    const clampDim = (v) => Math.min(20000, Math.max(0, Math.floor(Number(v) || 0)));
    const previewW = clampDim(request.data?.previewW);
    const previewH = clampDim(request.data?.previewH);
    const durationMs = Math.min(24 * 3600 * 1000, Math.max(0, Math.floor(Number(request.data?.durationMs) || 0)));

    if (priceCoins < MIN_PRICE_COINS || priceCoins > MAX_PRICE_COINS) {
      throw new HttpsError(
        'invalid-argument',
        `Price must be between ${MIN_PRICE_COINS} and ${MAX_PRICE_COINS} coins.`,
      );
    }
    // The key must belong to the caller. Without this check a caller could name
    // someone else's locked object and sell access to content they do not own.
    if (!mediaKey.startsWith(`locked/${uid}/`)) {
      throw new HttpsError('permission-denied', 'That file is not yours.');
    }
    if (previewUrl && !previewUrl.startsWith(`${publicBase()}/lockedpreview/${uid}/`)) {
      throw new HttpsError('permission-denied', 'That preview is not yours.');
    }

    // SCAN BEFORE SELLING. Plan section 3b: priced media is scanned for CSAM and
    // NCII only, and nudity passes. This is reached because the content carries
    // a PRICE, never because of where it lives; private unpaid conversation is
    // still not scanned at all and that does not change.
    //
    // The scanner takes a URL and this object has no public one, so it gets a
    // 60-second signed GET. That URL is never returned to anyone.
    let moderation = null;
    if (!isVideo) {
      const { scanPricedImage } = require('./contentAi');
      const scanUrl = await getSignedUrl(
        r2Client(),
        new GetObjectCommand({ Bucket: bucket(), Key: mediaKey }),
        { expiresIn: 60 },
      );
      const verdict = await scanPricedImage(scanUrl, process.env.GEMINI_POST_IMAGE_KEY);

      if (verdict.verdict === 'block') {
        // No post, and the message does not explain which signal tripped:
        // telling someone exactly what the classifier caught is a tuning guide
        // for the person you least want to help.
        throw new HttpsError(
          'failed-precondition',
          'This image cannot be sold on Vergr. If you believe that is wrong, contact support.',
        );
      }
      if (verdict.verdict === 'flag') {
        moderation = { status: 'review', category: verdict.category || 'none', reason: verdict.reason || '' };
      }
      // SELF-DECLARATION IS NOT TRUSTED. The seller ticks the NSFW box; the
      // scanner decides. A creator who forgets the toggle, or omits it to reach
      // a wider feed, gets the label applied anyway. Deliberately one-way: the
      // scanner can ADD the marker but never remove one the seller set, because
      // a false negative puts adult content in front of someone who did not
      // consent to it, while a false positive only narrows that seller's reach.
      if (verdict.adult === true) autoRating = 'nsfw';
    }

    const user = await db.collection('users').doc(uid).get();
    const u = user.exists ? user.data() : {};

    const postRef = db.collection('posts').doc();
    const batch = db.batch();

    batch.set(postRef, {
      authorId: uid,
      ...((contentRating || autoRating) ? { contentRating: 'nsfw' } : {}),
      authorName: u.displayName || u.username || 'Unknown',
      authorUsername: u.username || null,
      authorAvatar: u.avatar || null,
      content: caption,
      type: isVideo ? 'clip' : 'photo',
      // NO mediaUrl. That field is what every renderer reaches for, and leaving
      // it absent is what makes a client fall through to the locked state
      // instead of trying to show bytes it cannot have.
      locked: {
        priceCoins,
        previewUrl: previewUrl || null,
        unlockCount: 0,
        isVideo,
        audience,
        previewW,
        previewH,
        durationMs: isVideo ? durationMs : 0,
      },
      likes: 0,
      commentCount: 0,
      // A flagged post is created but NOT published, so it is invisible to every
      // feed query (they all filter status == 'published') and cannot be bought.
      // Created rather than refused so the creator's upload is not thrown away
      // over a classifier that was unsure.
      status: moderation ? 'review' : 'published',
      moderation,
      createdAt: FieldValue.serverTimestamp(),
    });

    // A flagged priced upload goes to the human queue with its verdict attached.
    if (moderation) {
      batch.set(db.collection('reports').doc(), {
        type: 'priced_media_review',
        postId: postRef.id,
        reportedUserId: uid,
        reason: `Automatic review: ${moderation.category} — ${moderation.reason}`,
        status: 'open',
        source: 'scanner',
        createdAt: FieldValue.serverTimestamp(),
      });
    }

    // Keyed by post id, so one document holds every locked file this creator
    // owns. Exactly the `vergrMeProductFiles` shape, and read only by getAccess.
    batch.set(
      db.collection('users').doc(uid).collection('private').doc('lockedPostFiles'),
      { [postRef.id]: { key: mediaKey, contentType: isVideo ? 'video' : 'image', createdAt: Date.now() } },
      { merge: true },
    );

    batch.update(db.collection('users').doc(uid), {
      postCount: FieldValue.increment(1),
    });

    await batch.commit();
    return { ok: true, postId: postRef.id };
  },
);
